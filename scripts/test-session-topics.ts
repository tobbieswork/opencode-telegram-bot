import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { StateManager } from "../src/state.js";
import { SessionTopics, type TopicSession, type SessionTopicPorts } from "../src/session-topics.js";

const root = mkdtempSync(join(tmpdir(), "session-topics-"));
const state = new StateManager(join(root, "state.json"));
const sessions = new Map<string, TopicSession>();
const calls: string[] = [];
let nextSession = 0;
let nextTopic = 100;
const ports: SessionTopicPorts = {
  createSession: async (input) => {
    const id = `ses_${++nextSession}`;
    sessions.set(id, { id, directory: input.directory, projectID: "project", createdAt: nextSession,
      source: "test", archived: false, busy: false, terminal: true });
    return id;
  },
  session: async (id) => {
    if (!sessions.has(id)) throw Object.assign(new Error("Missing session"), { name: "SessionNotFoundError" });
    return structuredClone(sessions.get(id)!);
  },
  createTopic: async () => { calls.push("create-topic"); return ++nextTopic; },
  archive: async (id, archived) => { calls.push(archived ? "archive" : "unarchive"); sessions.get(id)!.archived = archived; },
  closeTopic: async () => { calls.push("close-topic"); },
  openTopic: async () => { calls.push("open-topic"); },
  stop: async () => true,
};

try {
  const topics = new SessionTopics(state, ports);
  topics.enable("-1001");
  const link = await topics.create({ chat: "-1001", directory: root, title: "First", operationID: "create-first" });
  assert.equal(link.sessionID, "ses_1");
  assert.equal(link.conv, "-1001:101");
  assert.equal(link.phase, "open");
  assert.equal(state.findChatBySession("ses_1"), "-1001:101");
  assert.equal(state.peek("-1001")?.sessionID, undefined);
  assert.equal(topics.forTopic("-1001:101")?.sessionID, "ses_1");
  console.log("ok: General creates a fixed session/topic binding, never a General session");
  const [a, b] = await Promise.all([0, 1].map(() => topics.create({ chat: "-1001", directory: root,
    title: "Repeated tap", operationID: "same-action" })));
  assert.equal(a.id, b.id);
  assert.equal(nextSession, 2);
  assert.equal(calls.filter((call) => call === "create-topic").length, 2);
  const restarted = new SessionTopics(new StateManager(join(root, "state.json")), ports);
  assert.equal((await restarted.create({ chat: "-1001", directory: root, title: "Repeated tap", operationID: "same-action" })).id, a.id);
  assert.equal(nextSession, 2);
  console.log("ok: repeated create actions share one binding, including after restart");
  sessions.set("ses_external", { id: "ses_external", directory: root, projectID: "project", createdAt: 50,
    source: "test", archived: false, busy: false, terminal: true });
  const [attached, same] = await Promise.all([0, 1].map(() => topics.attach("-1001", "ses_external")));
  assert.equal(attached.id, same.id);
  assert.equal(attached.conv, "-1001:103");
  assert.equal(nextSession, 2);
  topics.enable("-1002");
  await assert.rejects(topics.attach("-1002", "ses_external"), /another chat/);
  assert.equal(state.findChatBySession("ses_external"), attached.conv);
  console.log("ok: attaching reuses one topic and refuses cross-chat ownership theft");
  const ordinaryStop = ports.stop;
  ports.stop = async () => false;
  assert.equal(await topics.stop("-1001", attached.id), false, "idle is not proof accepted by the execution owner");
  const ownerPending = await topics.close("-1001", attached.id);
  assert.equal(ownerPending.phase, "closing");
  assert.equal(sessions.get(attached.sessionID!)!.archived, false);
  ports.stop = ordinaryStop;
  await topics.reconcile(attached.sessionID);
  await topics.restore("-1001", attached.id);
  console.log("ok: the execution owner can block closure even when a generic snapshot looks idle");
  sessions.get("ses_1")!.busy = true;
  sessions.get("ses_1")!.terminal = false;
  let confirmed = false;
  ports.stop = async () => {
    calls.push("stop");
    if (confirmed) Object.assign(sessions.get("ses_1")!, { busy: false, terminal: true });
    return confirmed;
  };
  const closesBeforeBusy = calls.filter((call) => call === "close-topic").length;
  const pendingClose = await topics.close("-1001", link.id);
  assert.equal(pendingClose.phase, "closing");
  assert.equal(sessions.get("ses_1")!.archived, false);
  assert.equal(calls.filter((call) => call === "close-topic").length, closesBeforeBusy);
  confirmed = true;
  const recovered = new SessionTopics(new StateManager(join(root, "state.json")), ports);
  await recovered.reconcile("ses_1");
  assert.equal(recovered.get(link.id)?.phase, "closed");
  assert.deepEqual(calls.slice(-3), ["stop", "archive", "close-topic"]);
  assert.equal(state.peek(link.conv!)?.sessionID, "ses_1");
  console.log("ok: close waits for confirmed termination and resumes safely after restart");
  let closeFails = true;
  ports.closeTopic = async () => { calls.push("close-topic"); if (closeFails) throw new Error("Telegram permission denied"); };
  const incomplete = await recovered.close("-1001", a.id);
  assert.equal(incomplete.phase, "closing");
  assert.equal(sessions.get(a.sessionID!)!.archived, true);
  await assert.rejects(recovered.restore("-1001", a.id), /closing/);
  closeFails = false;
  await recovered.reconcile(a.sessionID);
  const restored = await recovered.restore("-1001", a.id);
  assert.equal(restored.phase, "open");
  assert.equal(restored.sessionID, a.sessionID);
  assert.equal(restored.conv, a.conv);
  assert.ok((restored.lifecycleRevision ?? 0) > (a.lifecycleRevision ?? 0), "Đóng rồi mở lại phải đổi mốc dù vẫn cùng phiên/chủ đề");
  assert.equal(nextTopic, 103);
  assert.deepEqual(calls.slice(-2), ["unarchive", "open-topic"]);
  console.log("ok: partial close stays pending; restore reuses the original session and topic");
  sessions.get(a.sessionID!)!.archived = true;
  await recovered.reconcile(a.sessionID);
  assert.equal(recovered.get(a.id)?.phase, "closed");
  sessions.get(a.sessionID!)!.archived = false;
  await recovered.reconcile(a.sessionID);
  assert.equal(recovered.get(a.id)?.phase, "open");
  sessions.delete(a.sessionID!);
  await recovered.reconcile(a.sessionID);
  assert.equal(recovered.get(a.id)?.phase, "missing");
  assert.equal(calls.at(-1), "close-topic");
  const archivedCount = calls.filter((call) => call === "archive").length;
  const originalSession = ports.session;
  ports.session = async () => { throw Object.assign(new Error("Denied"), { name: "UnauthorizedError" }); };
  const closesBefore = calls.filter((call) => call === "close-topic").length;
  await recovered.reconcile(link.sessionID);
  assert.equal(recovered.get(link.id)?.phase, "attention");
  assert.equal(calls.filter((call) => call === "close-topic").length, closesBefore);
  assert.equal(calls.filter((call) => call === "archive").length, archivedCount);
  ports.session = originalSession;
  await recovered.reconcile(link.sessionID);
  assert.equal(recovered.get(link.id)?.phase, "closed");
  console.log("ok: missed archive/restore/delete events reconcile; permission failures never mean deleted");
  ports.createTopic = async () => { calls.push("ambiguous-topic"); throw new Error("Response lost after Telegram accepted"); };
  await assert.rejects(recovered.create({ chat: "-1001", directory: root, title: "Ambiguous", operationID: "lost-create" }));
  const uncertain = recovered.list("-1001").find((item) => item.operationID === "lost-create")!;
  assert.equal(uncertain.phase, "attention");
  assert.ok(uncertain.sessionID);
  const attempts = calls.filter((call) => call === "ambiguous-topic").length;
  const afterCrash = new SessionTopics(new StateManager(join(root, "state.json")), ports);
  await afterCrash.reconcile();
  await assert.rejects(afterCrash.create({ chat: "-1001", directory: root, title: "Ambiguous", operationID: "lost-create" }), /blindly/);
  assert.equal(calls.filter((call) => call === "ambiguous-topic").length, attempts);
  assert.equal(afterCrash.get(uncertain.id)?.phase, "attention");
  console.log("ok: ambiguous topic creation is retained for intervention, never blindly replayed");
  ports.createTopic = async () => ++nextTopic;
  ports.configure = async () => { throw new Error("Configuration did not finish"); };
  await assert.rejects(afterCrash.create({ chat: "-1001", directory: root, title: "Incomplete configuration", operationID: "configure-failed" }));
  const unconfigured = afterCrash.list().find((item) => item.operationID === "configure-failed")!;
  assert.ok(unconfigured.conv);
  await afterCrash.reconcile(unconfigured.sessionID);
  assert.equal(afterCrash.get(unconfigured.id)?.phase, "attention");
  assert.equal(afterCrash.canPrompt(unconfigured.conv!), false);
  console.log("ok: a partially configured session never becomes runnable through reconciliation");
  await assert.rejects(async () => afterCrash.close("-1001", uncertain.id), /incomplete|ready/i);
  assert.equal(afterCrash.get(uncertain.id)?.phase, "attention");
  assert.ok(afterCrash.list().some((item) => item.id === link.id), "an incomplete operation must not corrupt the lifecycle store");
  console.log("ok: close cannot promote an incomplete creation into an invalid lifecycle state");
  await afterCrash.close("-1001", unconfigured.id);
  const retriedConfiguration = await afterCrash.restore("-1001", unconfigured.id);
  assert.notEqual(retriedConfiguration.phase, "open");
  assert.equal(afterCrash.canPrompt(unconfigured.conv!), false);
  console.log("ok: close/restore cannot bypass incomplete first-time configuration");
  const damaged = JSON.parse(readFileSync(join(root, "state.json"), "utf8"));
  damaged[link.conv!].sessionID = "ses_somebody_else";
  writeFileSync(join(root, "state.json"), JSON.stringify(damaged));
  const inconsistent = new SessionTopics(new StateManager(join(root, "state.json")), ports);
  const mutationsBefore = calls.length;
  const rejectedClose = await inconsistent.close("-1001", link.id);
  assert.equal(rejectedClose.phase, "attention");
  assert.equal(inconsistent.canPrompt(link.conv!), false);
  assert.equal(calls.length, mutationsBefore, "ambiguous local ownership cannot stop/archive/close anything");
  console.log("ok: a mismatched conversation binding fails closed without remote side effects");
  const badFile = join(root, "unsupported.json");
  writeFileSync(badFile, JSON.stringify({ __machine__: { sessionTopics: { version: 99, groups: {}, links: {} } } }));
  const unsupported = new SessionTopics(new StateManager(badFile), ports);
  await assert.rejects(async () => unsupported.enable("-1001"), /Unsupported|invalid/);
  assert.equal(JSON.parse(readFileSync(badFile, "utf8")).__machine__.sessionTopics.version, 99);
  console.log("ok: unsupported lifecycle state is preserved and cannot admit new work");
  const sharedFile = join(root, "shared-legacy.json");
  writeFileSync(sharedFile, JSON.stringify({ "-1001": { sessionID: "ses_1" }, "-1002": { sessionID: "ses_1" } }));
  const shared = new SessionTopics(new StateManager(sharedFile), ports);
  shared.enable("-1001");
  await assert.rejects(shared.attach("-1001", "ses_1"), /conflict|multiple/i);
  assert.equal(shared.list().length, 0);
  console.log("ok: a legacy session shared by multiple chats cannot be silently claimed");
  const generalFile = join(root, "legacy-general-topic.json");
  sessions.set("ses_legacy_general", { ...sessions.get("ses_1")!, id: "ses_legacy_general", archived: true });
  writeFileSync(generalFile, JSON.stringify({ "-1001:1": { sessionID: "ses_legacy_general" } }));
  const generalLegacy = new SessionTopics(new StateManager(generalFile), ports);
  generalLegacy.enable("-1001");
  await assert.rejects(generalLegacy.attach("-1001", "ses_legacy_general"), /lưu trữ/);
  assert.equal(generalLegacy.list().length, 0);
  sessions.get("ses_legacy_general")!.archived = false;
  const migratedGeneral = await generalLegacy.attach("-1001", "ses_legacy_general");
  assert.notEqual(migratedGeneral.conv, "-1001:1");
  assert.notEqual(migratedGeneral.conv, "-1001");
  assert.equal(generalLegacy.canPrompt(migratedGeneral.conv!), true);
  console.log("ok: explicit migration moves a legacy General-thread session to a real work topic");
  const ordinarySnapshot = ports.session;
  ports.configure = undefined;
  ports.session = async (id) => ({ ...await ordinarySnapshot(id), id: "ses_wrong_response" });
  await assert.rejects(generalLegacy.create({ chat: "-1001", directory: root, title: "Wrong identity", operationID: "wrong-identity" }));
  assert.equal(generalLegacy.list().find((item) => item.operationID === "wrong-identity")?.conv, undefined);
  ports.session = ordinarySnapshot;
  console.log("ok: a creation cannot bind a snapshot returned for a different session");
  ports.createTopic = async () => 1;
  await assert.rejects(generalLegacy.create({ chat: "-1001", directory: root, title: "Invalid Telegram response", operationID: "invalid-thread" }));
  assert.equal(generalLegacy.list().find((item) => item.operationID === "invalid-thread")?.phase, "attention");
  assert.equal(generalLegacy.canPrompt(migratedGeneral.conv!), true);
  console.log("ok: malformed topic responses do not corrupt unrelated managed sessions");
  const interruptedFile = JSON.parse(readFileSync(generalFile, "utf8"));
  const interruptedLink = Object.values(interruptedFile.__machine__.sessionTopics.links).find((item: any) => item.operationID === "invalid-thread") as any;
  interruptedLink.phase = "creating";
  writeFileSync(generalFile, JSON.stringify(interruptedFile));
  const interruptedCreation = new SessionTopics(new StateManager(generalFile), ports);
  await interruptedCreation.reconcile(interruptedLink.sessionID);
  assert.equal(interruptedCreation.get(interruptedLink.id)?.phase, "attention");
  console.log("ok: a crash during creation becomes visible intervention, not endless fake progress");
  ports.stop = async () => false;
  await interruptedCreation.close("-1001", migratedGeneral.id);
  sessions.delete(migratedGeneral.sessionID!);
  await interruptedCreation.reconcile(migratedGeneral.sessionID);
  assert.equal(interruptedCreation.get(migratedGeneral.id)?.phase, "missing");
  console.log("ok: session deletion during a pending close still closes the topic without claiming execution proof");
} finally { rmSync(root, { recursive: true, force: true }); }
