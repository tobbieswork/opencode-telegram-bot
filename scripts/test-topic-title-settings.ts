import assert from "node:assert/strict";
import { Bot } from "../src/bot.js";
import { StateManager } from "../src/state.js";
import { workflowBot } from "./fixtures/bot-workflow.js";

const f = workflowBot();
let restored: Bot | undefined;
const names: string[] = [];
let renameError: Error | undefined;
f.oc.topicSessionTitle = async id => structuredClone(f.observations.get(id)!.info);
f.tg.editForumTopic = async (conv, name) => { if (renameError) throw renameError; if (conv === "-1001:200") names.push(name); };
const button = (suffix: string) => f.buttons().find(button => button.callback_data?.endsWith(suffix))!.callback_data!;
try {
  await f.bot.handle(f.tap("tc:open:group"));
  assert.ok(f.sent.at(-1)?.text.includes("Thiết lập tên"));
  const off = button(":off");
  await f.bot.handle(f.tap(off, 2));
  assert.equal(f.st.sessionTopics()?.titlePolicies, undefined);
  await f.bot.handle(f.tap(off, 1, -1002));
  assert.equal(f.st.sessionTopics()?.titlePolicies, undefined);
  await f.bot.handle(f.tap(off, 1, -1001, 202));
  assert.equal(f.st.sessionTopics()?.titlePolicies, undefined);
  await f.bot.handle(f.tap(off));
  assert.equal(f.st.sessionTopics()?.titlePolicies?.groups["-1001"].enabled, false);
  assert.ok(f.sent.at(-1)?.text.includes("Tắt"));
  assert.equal(names.length, 0);
  await f.bot.handle(f.tap("st:title-preview:0"));
  const stale = f.buttons().find(button => button.callback_data?.startsWith("st:title-enable:"))!.callback_data!;
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  await f.bot.handle(f.tap(button(":keep")));
  assert.equal(f.st.sessionTopics()?.links["0000000000000001"].titlePolicy?.mode, "keep");
  await f.bot.handle(f.tap(stale));
  assert.equal(f.st.sessionTopics()?.titlePolicies?.groups["-1001"].enabled, false);
  await f.bot.handle(f.tap("st:title-preview:0"));
  await f.bot.handle(f.tap(f.buttons().find(button => button.callback_data?.startsWith("st:title-enable:"))!.callback_data!));
  assert.equal(f.st.sessionTopics()?.titlePolicies?.groups["-1001"].enabled, true);
  assert.equal(f.st.sessionTopics()?.links["0000000000000001"].titlePolicy?.mode, "keep");
  await f.bot.handle(f.tap("st:title-sync:0000000000000001"));
  assert.equal(names.length, 0, "Thử lại không bật theo OpenCode cho ngoại lệ đang giữ tên");
  f.observations.get("ses_fixture_0")!.info.title = "Tên <mới> từ OpenCode";
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  await f.bot.handle(f.tap(button(":preview")));
  assert.ok(f.sent.at(-1)?.text.includes("Tên &lt;mới&gt; từ OpenCode"));
  const confirm = button(":confirm");
  await f.bot.handle(f.tap(confirm, 2));
  assert.equal(f.st.sessionTopics()?.links["0000000000000001"].titlePolicy?.mode, "keep");
  await f.bot.handle(f.tap(confirm));
  assert.equal(f.st.sessionTopics()?.links["0000000000000001"].titlePolicy?.mode, "follow");
  const deadline = Date.now() + 8000;
  while (!names.includes("Tên <mới> từ OpenCode") && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 20));
  assert.ok(names.includes("Tên <mới> từ OpenCode"));
  f.observations.get("ses_fixture_0")!.info.title = "Tên chờ <khác>";
  renameError = new Error("Thiếu <quyền> đổi tên");
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  await f.bot.handle(f.tap(button(":retry")));
  const errorDeadline = Date.now() + 4000;
  while (!f.st.sessionTopics()?.links["0000000000000001"].titleSync?.error && Date.now() < errorDeadline) await new Promise(resolve => setTimeout(resolve, 20));
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  assert.ok(f.sent.at(-1)?.text.includes("Ý định tên đã lưu: Tên chờ &lt;khác&gt;"));
  assert.ok(f.sent.at(-1)?.text.includes("Thiếu &lt;quyền&gt;"));
  assert.equal(f.st.sessionTopics()?.links["0000000000000001"].title, "Tên <mới> từ OpenCode");
  renameError = undefined;
  const data = f.st.sessionTopics()!;
  data.titleRetryAt = { "-1001": Date.now() + 60_000 };
  f.st.commitSessionTopics(data);
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  assert.ok(f.sent.at(-1)?.text.includes("Thử lại không sớm hơn"));
  const retry = button(":retry");
  const count = names.length;
  await f.bot.handle(f.tap(retry));
  assert.equal(names.length, count, "Không vượt thời gian chờ Telegram bằng nút thử lại");
  await f.bot.handle(f.tap("tc:open:group"));
  await f.bot.handle(f.tap(button(":off")));
  assert.equal(f.st.sessionTopics()?.titlePolicies?.groups["-1001"].enabled, false);
  await f.bot.handle(f.tap("tc:open:0000000000000001"));
  const validBeforeRestart = button(":preview");
  f.bot.stopScheduler();
  restored = new Bot(f.tg, f.oc, new StateManager(f.cfg.stateFile), f.cfg);
  await restored.handle(f.tap("tc:open:0000000000000001"));
  assert.ok(f.sent.at(-1)?.text.includes("Theo OpenCode"));
  assert.ok(f.sent.at(-1)?.text.includes("Tắt"));
  assert.ok(f.sent.at(-1)?.text.includes("Thử lại không sớm hơn"));
  await restored.handle(f.tap(validBeforeRestart));
  assert.ok(f.sent.at(-1)?.text.includes("hết hạn"));
  assert.equal(names.length, count);
  assert.equal(f.effects.length, 0);
  console.log("Đạt: công tắc nhóm/chủ đề có phạm vi, xem trước trước khi bật, thẻ cũ bị chặn, thử lại không vượt giới hạn và khởi động lại giữ chính sách.");
} finally { restored?.stopScheduler(); f.dispose(); }
