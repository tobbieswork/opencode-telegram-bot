import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { SessionTopics } from "../src/session-topics.js";
import { StateManager } from "../src/state.js";
import { topicTitle } from "../src/format.js";
import { workflowFixture, deferred } from "./fixtures/workflow.js";

const root = mkdtempSync(join(tmpdir(), "custom-titles-"));
const fixture = workflowFixture();
const st = new StateManager(join(root, "state.json"));
for (const [conv, state] of Object.entries(fixture.states)) st.set(conv, state);
st.commitSessionTopics(fixture.topics);
let now = fixture.now;
const writes: string[] = [];
let rename: ((name: string) => Promise<void>) | undefined;
const forbidden = async (): Promise<never> => { throw new Error("Không đổi vòng đời hoặc tạo công việc"); };
const ports = { createSession: forbidden, session: forbidden, createTopic: forbidden, archive: forbidden,
  closeTopic: forbidden, openTopic: forbidden, stop: forbidden, now: () => now,
  sessionTitle: async (id: string) => ({ ...fixture.sessions[id], title: "Tên A từ OpenCode" }),
  renameTopic: async (_conv: string, name: string) => { await rename?.(name); writes.push(name); } };
const topics = new SessionTopics(st, ports);
let restored: SessionTopics | undefined;
try {
  const id = "0000000000000001";
  const started = deferred<void>();
  const finish = deferred<void>();
  rename = async () => { started.resolve(); await finish.promise; };
  const old = topics.syncTitle("-1001", id, true);
  await started.promise;
  topics.queueCustomTitle("-1001", id, "Tên B riêng", topics.titleScopeStamp("-1001", id));
  assert.equal(topics.canPrompt("-1001:200"), true);
  finish.resolve();
  await old;
  assert.equal(topics.get(id)?.title, "Tên A từ OpenCode");
  assert.equal(topics.titlePolicy("-1001", id).customName, "Tên B riêng");
  assert.equal(topics.titleStatus("-1001", id).pendingName, "Tên B riêng");
  rename = undefined;
  now += 2000;
  await topics.syncTitle("-1001", id);
  assert.equal(topics.get(id)?.title, "Tên B riêng");
  assert.equal(topics.titleStatus("-1001", id).pending, false);
  const done = writes.length;
  topics.observeTopicTitle("-1001:200", "Tên sửa tay sau đó");
  await topics.syncTitle("-1001", id, true);
  assert.equal(writes.length, done, "Tên riêng không bị kéo về OpenCode hoặc tự ép lại sau khi người dùng sửa Telegram");

  topics.setTitleGroupSync("-1001", false);
  const long = topicTitle("  Tên <Việt>\n" + "👨‍👩‍👧‍👦".repeat(50));
  topics.queueCustomTitle("-1001", id, long, topics.titleScopeStamp("-1001", id));
  const failure = Object.assign(new Error("Giới hạn tần suất"), { code: 429, retryAfter: 30 });
  rename = async () => { throw failure; };
  now += 2000;
  assert.equal((await topics.syncTitle("-1001", id)).status, "failed");
  assert.equal(topics.get(id)?.title, "Tên B riêng");
  assert.equal(topics.titleStatus("-1001", id).pendingName, long);
  topics.stopTitleSync();
  rename = undefined;
  restored = new SessionTopics(new StateManager(join(root, "state.json")), ports);
  assert.equal((await restored.syncTitle("-1001", id)).status, "waiting");
  assert.equal(writes.length, done);
  now += 31_000;
  assert.equal((await restored.syncTitle("-1001", id)).status, "synced");
  assert.equal(restored.get(id)?.title, long);
  assert.equal(restored.titleSyncEnabled("-1001"), false, "Đặt thủ công không tự bật nhóm");
  const closed = "0000000000000004";
  restored.queueCustomTitle("-1001", closed, "Tên chờ mở", restored.titleScopeStamp("-1001", closed));
  assert.equal((await restored.syncTitle("-1001", closed)).status, "waiting");
  assert.equal(restored.get(closed)?.phase, "closed");
  assert.equal(restored.titleStatus("-1001", closed).pendingName, "Tên chờ mở");
  assert.throws(() => restored!.queueCustomTitle("-1002", id, "Sai nhóm", restored!.titleScopeStamp("-1002")));
  restored.setTitlePolicy("-1001", id, { mode: "follow" });
  restored.setTitleGroupSync("-1001", true);
  now += 2000;
  const errorStarted = deferred<void>();
  const errorFinish = deferred<void>();
  rename = async () => { errorStarted.resolve(); await errorFinish.promise; throw failure; };
  const lateError = restored.syncTitle("-1001", id, true);
  await errorStarted.promise;
  restored.queueCustomTitle("-1001", id, "Tên sau lỗi cũ", restored.titleScopeStamp("-1001", id));
  errorFinish.resolve();
  assert.equal((await lateError).status, "disabled");
  assert.equal(restored.titleStatus("-1001", id).pendingName, "Tên sau lỗi cũ");
  assert.equal((await restored.syncTitle("-1001", id)).status, "waiting");
  rename = undefined;
  now += 31_000;
  await restored.syncTitle("-1001", id);
  assert.equal(restored.get(id)?.title, "Tên sau lỗi cũ");

  now += 2000;
  let remoteTitle = "Tên sau lỗi cũ";
  let loseResponse = true;
  rename = async name => { remoteTitle = name; if (loseResponse) { loseResponse = false; throw new Error("Mất phản hồi sau khi đã gửi"); } };
  restored.queueCustomTitle("-1001", id, "Tên đã gửi nhưng chưa xác nhận", restored.titleScopeStamp("-1001", id));
  assert.equal((await restored.syncTitle("-1001", id)).status, "failed");
  assert.equal(remoteTitle, "Tên đã gửi nhưng chưa xác nhận");
  assert.equal(restored.get(id)?.title, "Tên sau lỗi cũ", "Không đoán thành công khi mất phản hồi");
  now += 5000;
  await restored.syncTitle("-1001", id);
  assert.equal(restored.get(id)?.title, remoteTitle);
  restored.setTitleGroupSync("-1001", false);
  restored.queueCustomTitle("-1001", id, "Tên phục hồi trước lần ghi đầu", restored.titleScopeStamp("-1001", id));
  restored.stopTitleSync();
  const restartStore = new StateManager(join(root, "state.json"));
  restored = new SessionTopics(restartStore, ports);
  assert.equal(restored.titleStatus("-1001", id).pendingName, "Tên phục hồi trước lần ghi đầu");
  now += 2000;
  await restored.syncTitle("-1001", id);
  assert.equal(restored.get(id)?.title, "Tên phục hồi trước lần ghi đầu");
  restored.queueCustomTitle("-1001", id, "Không áp vào danh tính mới", restored.titleScopeStamp("-1001", id));
  const identityChanged = restartStore.sessionTopics()!;
  identityChanged.links[id].identity!.source = "nguon-khac";
  restartStore.commitSessionTopics(identityChanged);
  assert.equal((await restored.syncTitle("-1001", id)).status, "disabled");
  assert.equal(restored.get(id)?.title, "Tên phục hồi trước lần ghi đầu");
  console.log("Đạt: phản hồi cũ không đè ý định mới, tên riêng một lần không bật nhóm, 429/khởi động lại giữ ý định và tên đã xác nhận, chủ đề đóng không bị mở lại.");
} finally { restored?.stopTitleSync(); topics.stopTitleSync(); rmSync(root, { recursive: true, force: true }); }
