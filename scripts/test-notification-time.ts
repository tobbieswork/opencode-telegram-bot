import assert from "node:assert/strict";
import { quietUntil, validateQuiet, type QuietHours } from "../src/notification-time.js";
import { Notifications, type Notice } from "../src/notifications.js";
import { snoozeSchedule } from "../src/reminders.js";
import { StateManager } from "../src/state.js";
import { workflowBot } from "./fixtures/bot-workflow.js";

const policy: QuietHours = { enabled: true, start: "23:00", end: "07:00", timeZone: "UTC", urgent: ["question", "permission", "blocked"] };
const time = Date.parse;
assert.equal(quietUntil(policy, time("2026-10-29T22:59:59Z")), undefined);
assert.equal(quietUntil(policy, time("2026-10-29T23:00:00Z")), time("2026-10-30T07:00:00Z"));
assert.equal(quietUntil(policy, time("2026-10-30T07:00:00Z")), undefined);
assert.equal(quietUntil({ ...policy, timeZone: "Asia/Ho_Chi_Minh" }, time("2026-10-29T16:00:00Z")), time("2026-10-30T00:00:00Z"));
assert.equal(quietUntil({ ...policy, start: "01:30", end: "03:30", timeZone: "America/New_York" }, time("2026-03-08T06:45:00Z")), time("2026-03-08T07:30:00Z"));
assert.equal(quietUntil({ ...policy, start: "01:00", end: "02:30", timeZone: "America/New_York" }, time("2026-03-08T06:30:00Z")), time("2026-03-08T07:00:00Z"));
for (const hour of ["05", "06"]) assert.equal(quietUntil({ ...policy, start: "01:15", end: "01:45", timeZone: "America/New_York" }, time(`2026-11-01T${hour}:30:00Z`)), time(`2026-11-01T${hour}:45:00Z`));
assert.throws(() => validateQuiet({ ...policy, end: "23:00" }));
assert.throws(() => validateQuiet({ ...policy, start: "25:00" }));
assert.throws(() => validateQuiet({ ...policy, timeZone: "Khong/Co" }));
assert.deepEqual(snoozeSchedule({ nextReminderAt: 100 }, 1000), { nextReminderAt: 1000, snoozeBaseAt: 100, snoozedUntil: 1000 });
assert.deepEqual(snoozeSchedule({ nextReminderAt: 1000, snoozeBaseAt: 100 }), { nextReminderAt: 100, snoozeBaseAt: undefined, snoozedUntil: undefined });

const f = workflowBot();
let now = time("2026-10-29T23:30:00Z");
const deliveries: string[] = [];
let hold = 0;
let valid = true;
const ports = { now: () => now, deliver: async (_chat: string, text: string) => { deliveries.push(text); return deliveries.length; },
  resolve: async (event: Notice) => valid ? event : undefined, holdUntil: () => hold };
const center = new Notifications(f.st, ports);
try {
  center.configure("-1001", 0, true);
  center.configureQuiet("-1001", 1, policy);
  const event: Notice = { chat: "-1001", conv: "-1001:200", linkID: "0000000000000001", sessionID: "ses_fixture_0", binding: "fixture", kind: "completed",
    title: "Phiên thử", occurredAt: now, reference: { kind: "input", id: "input_quiet" } };
  for (let n = 0; n < 12; n++) center.enqueue({ ...event, reference: { kind: "input", id: `input_${n}` } });
  now += 5000; await center.flush(); assert.equal(deliveries.length, 0);
  center.enqueue({ ...event, kind: "question", reference: { kind: "form", id: "urgent" } });
  await center.flush(); assert.equal(deliveries.length, 1, "Khẩn theo loại đã xác nhận, không hoãn thẻ gốc");
  now = time("2026-10-30T07:00:00Z");
  const restarted = new Notifications(f.st, ports);
  await restarted.flush(); assert.equal(deliveries.length, 2);
  await restarted.flush(); assert.equal(deliveries.length, 2, "Không bắn dồn sau giờ yên lặng");
  now += 5000; await restarted.flush(); assert.equal(deliveries.length, 3);
  hold = now + 900_000;
  center.enqueue({ ...event, kind: "question", occurredAt: now, reference: { kind: "form", id: "paused" } });
  await center.flush(); assert.equal(deliveries.length, 3);
  valid = false; now = hold;
  await center.flush(); assert.equal(deliveries.length, 3, "Đã giải quyết trong lúc hoãn thì bỏ, không hỏi lại");
  valid = true; hold = 0;
  now = time("2026-10-30T23:30:00Z");
  center.enqueue({ ...event, occurredAt: now, reference: { kind: "input", id: "policy_change" } });
  now += 5000; await center.flush(); assert.equal(deliveries.length, 3);
  const settings = center.settings("-1001");
  center.configureQuiet("-1001", settings.revision, { ...policy, enabled: false });
  await center.flush(); assert.equal(deliveries.length, 4, "Đổi chính sách tính lại cả mục đang hoãn");

  await f.bot.handle(f.tap("nt:quiet"));
  const promptID = f.sent.length;
  const reply = f.message("22:00 06:00 Asia/Ho_Chi_Minh");
  reply.message!.reply_to_message = { message_id: promptID };
  const timezone = f.cfg.scheduleTz;
  await f.bot.handle(reply);
  const save = f.buttons().find(button => button.callback_data?.startsWith("nt:qsave:"))!.callback_data!;
  const prior = f.st.peek("-1001")!.notificationSettings;
  await f.bot.handle(f.tap(save, 2)); assert.deepEqual(f.st.peek("-1001")!.notificationSettings, prior);
  await f.bot.handle(f.tap(save));
  assert.equal(f.st.peek("-1001")!.notificationSettings!.quiet!.timeZone, "Asia/Ho_Chi_Minh");
  assert.equal(f.cfg.scheduleTz, timezone);
  await f.bot.handle(f.tap("pa:list:0000000000000003:0"));
  const snooze = f.buttons().find(button => button.callback_data?.startsWith("pa:s15:"))!.callback_data!;
  const before = structuredClone(f.st.peek("-1001:202")!.pendingPrompts!);
  await f.bot.handle(f.tap(snooze, 2)); assert.deepEqual(f.st.peek("-1001:202")!.pendingPrompts, before);
  await f.bot.handle(f.tap(snooze));
  const after = f.st.peek("-1001:202")!.pendingPrompts!;
  const id = Object.keys(after).find(id => after[id].snoozedUntil)!;
  assert.ok(id);
  assert.equal(after[id].remindersSent, before[id].remindersSent);
  assert.equal(new StateManager(f.cfg.stateFile).peek("-1001:202")!.pendingPrompts![id].snoozedUntil, after[id].snoozedUntil);
  const relay = f.buttons().find(button => button.callback_data?.startsWith("pa:relay:"))!.callback_data!;
  await f.bot.handle(f.tap(relay));
  assert.equal(f.st.peek("-1001:202")!.pendingPrompts![id].snoozedUntil, after[id].snoozedUntil, "Hiển thị lại không làm mất tạm hoãn");
  await f.bot.handle(f.tap("pa:list:0000000000000003:0"));
  const wake = f.buttons().find(button => button.callback_data?.startsWith("pa:wake:"))!.callback_data!;
  await f.bot.handle(f.tap(wake));
  assert.equal(f.st.peek("-1001:202")!.pendingPrompts![id].nextReminderAt, before[id].nextReminderAt);
  assert.equal(f.effects.length, 0);
  console.log("Đạt: ranh giới/múi giờ/giờ mùa, gộp không dồn, đổi chính sách, nhập/xác nhận đúng người và hoãn đúng yêu cầu bền vững không đổi ngân sách/lịch chạy.");
} finally { center.stop(); f.dispose(); }
